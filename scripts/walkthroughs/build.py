"""Build src/content/walkthroughs/<Part>/<section>.json, and the index.ts that imports them, from the sources in this folder.

Usage: python3 scripts/walkthroughs/build.py [--check] [repo_dir]   (default: the repository this file is in)

A source is scripts/walkthroughs/<Part>/<section>.py. It defines WALK, built with kit.py. The build checks it
(check.py: the language rules, the layout and the kinds the site draws; this file: the size rules) and then writes
the JSON the site loads. See README.md.

--check writes nothing. It builds the files in memory and exits 1 when one on disk differs from its source, is
missing, or has no source at all. A build refuses to run beside a file with no source, and never deletes one.

Part 18 is not built here: its walk-throughs are inline in src/content/system-design.json (scripts/system-design).
"""
import importlib.util
import json
import math
import os
import re
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import check  # noqa: E402
from check import err, errors  # noqa: E402

ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
CHECK = "--check" in sys.argv[1:]
REPO = os.path.abspath(ARGS[0]) if ARGS else os.path.dirname(os.path.dirname(HERE))
SOURCES = os.path.join(REPO, "scripts", "walkthroughs")
OUT = os.path.join(REPO, "src", "content", "walkthroughs")

# The size rules of a walk-through that sits above a short section (docs/content-guide.md).
STEPS = (6, 9)
MAX_PARAGRAPHS = 2
MAX_BOXES_SHOWN = 8  # in one step: more is hard to read
MAX_BOXES = 12  # in all, boxes that come and go included
MAX_READOUTS = 4
# Room to read the diagram. Part 18 has tighter ones, so these are not in check.py.
MIN_EDGE = 10  # px from a box to the left, right and bottom edge of the diagram
MIN_TOP = 15  # px from the top of a box to the top edge: 9 for the badge above the box, 6 to spare
MIN_LINE = 20  # px of a line that shows between its two boxes, so its arrowhead can be seen

INDEX_HEAD = "// Generated by scripts/walkthroughs/build.py from the sources next to it in scripts/walkthroughs. Do not edit.\n"


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def rel(path):
    return os.path.relpath(path, REPO).replace(os.sep, "/")


def quoted_list(text, pattern, what):
    m = re.search(pattern, text, re.S)
    if not m:
        sys.exit(f"cannot find {what}")
    return re.findall(r'"([^"]+)"', m.group(1))


def check_size(w, where):
    """The rules that keep a walk-through short enough to sit above a section. Part 18 has longer ones, so these are not in check.py."""
    n = len(w["steps"])
    if not STEPS[0] <= n <= STEPS[1]:
        err(f"{where}: {n} steps, a walk-through has {STEPS[0]} to {STEPS[1]}")
    if len(w["nodes"]) > MAX_BOXES:
        err(f"{where}: {len(w['nodes'])} boxes in all, at most {MAX_BOXES}")
    if len(w["metrics"]) > MAX_READOUTS:
        err(f"{where}: {len(w['metrics'])} readouts, at most {MAX_READOUTS}")
    for i, st in enumerate(w["steps"], 1):
        if len(st["show"]) > MAX_BOXES_SHOWN:
            err(f"{where}.step{i}: {len(st['show'])} boxes shown, at most {MAX_BOXES_SHOWN}")
        for lang in ("en", "bn"):
            paragraphs = len(st[lang]["body"])
            if paragraphs > MAX_PARAGRAPHS:
                err(f"{where}.step{i}: {paragraphs} paragraphs, at most {MAX_PARAGRAPHS}")
            break  # en and bn have the same count (check_walk), so say it once


def check_room(w, where):
    """No box jammed against the edge of the diagram, and every line long enough to see its arrow. Both languages are
    measured, because Bangla labels make a box wider and can close the gap that English leaves."""
    for lang in ("en", "bn"):
        widths = check.node_widths(w, lang)
        for i, st in enumerate(w["steps"], 1):
            at = f"{where}.step{i}.{lang}"
            boxes = check.step_boxes(w, st, widths)
            for k, b in boxes.items():
                room = {"left": b["x"] - b["w"] / 2, "right": w["width"] - (b["x"] + b["w"] / 2), "bottom": w["height"] - (b["y"] + b["h"] / 2)}
                for side, px in room.items():
                    if px < MIN_EDGE:
                        err(f"{at}: {k} is {px:.0f}px from the {side} edge, at least {MIN_EDGE}px")
                top = b["y"] - b["h"] / 2
                if top < MIN_TOP:
                    err(f"{at}: {k} is {top:.0f}px from the top edge, at least {MIN_TOP}px")
            for l in st["links"]:
                if l["from"] in boxes and l["to"] in boxes:
                    a, b = boxes[l["from"]], boxes[l["to"]]
                    x1, y1 = check.box_exit(a, b["x"], b["y"])
                    x2, y2 = check.box_exit(b, a["x"], a["y"])
                    seg = math.hypot(x2 - x1, y2 - y1)
                    if seg < MIN_LINE:
                        err(f"{at}: the line {l['from']} → {l['to']} shows only {seg:.0f}px, at least {MIN_LINE}px")


def english_words(w):
    text = []
    for st in w["steps"]:
        t = st["en"]
        text += [t["title"], *t["body"], *t.get("points", [])]
        text += [c["html"] for c in t.get("changes", [])]
        if "note" in t:
            text.append(t["note"]["html"])
    return len(re.findall(r"[\w'’-]+", check.strip_html(" ".join(text))))


def load_walk(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None, f"cannot load {path}"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return getattr(module, "WALK", None)


def index_ts(entries):
    """entries: [(slug, [(section id, import name)])] in Part order."""
    if not entries:
        return INDEX_HEAD + "\nexport const WALKTHROUGH_FILES: Record<string, Record<string, unknown>> = {};\n"
    lines = [INDEX_HEAD]
    for slug, sections in entries:
        lines += [f'import {name} from "./{slug}/{sid}.json";' for sid, name in sections]
    lines += ["", "export const WALKTHROUGH_FILES: Record<string, Record<string, unknown>> = {"]
    for slug, sections in entries:
        lines.append(f'  "{slug}": {{')
        for sid, name in sections:
            key = sid if re.fullmatch(r"[A-Za-z_$][\w$]*", sid) else f'"{sid}"'
            lines.append(f"    {key}: {name},")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def camel(slug, sid):
    head, *rest = re.split(r"[^A-Za-z0-9]+", slug)
    return head + "".join(p.capitalize() for p in rest) + "".join(p.capitalize() for p in re.split(r"[^A-Za-z0-9]+", sid))


def main():
    order = quoted_list(read(os.path.join(REPO, "src/lib/topics.ts")), r"TOPIC_ORDER[^=]*=\s*\[(.*?)\]", "TOPIC_ORDER in src/lib/topics.ts")
    kinds = quoted_list(read(os.path.join(REPO, "src/lib/content-schema.ts")), r"WALK_NODE_KINDS\s*=\s*\[(.*?)\]\s*as const", "WALK_NODE_KINDS in src/lib/content-schema.ts")

    found = []  # (slug, section id, path)
    for slug in sorted(os.listdir(SOURCES)) if os.path.isdir(SOURCES) else []:
        folder = os.path.join(SOURCES, slug)
        if not os.path.isdir(folder) or slug.startswith(("_", ".")):
            continue
        for name in sorted(os.listdir(folder)):
            if name.endswith(".py") and not name.startswith("_"):
                found.append((slug, name[:-3], os.path.join(folder, name)))

    parts = {}  # slug -> the Part file's sections, in order
    built = {}  # (slug, section id) -> walk
    bad_parts = set()
    for slug, sid, path in found:
        where = f"{slug}/{sid}"
        if slug not in order:
            if slug not in bad_parts:
                err(f"{slug}: not a Part (it is not in TOPIC_ORDER in src/lib/topics.ts)")
                bad_parts.add(slug)
            continue
        if slug not in parts:
            part_path = os.path.join(REPO, "src", "content", f"{slug}.json")
            if not os.path.exists(part_path):
                err(f"{slug}: there is no {rel(part_path)}")
                bad_parts.add(slug)
                continue
            parts[slug] = json.loads(read(part_path))["sections"]
        section = next((s for s in parts[slug] if s["id"] == sid), None)
        if section is None:
            err(f'{where}: {slug} has no section "{sid}"')
            continue
        if "walkthrough" in section:
            err(f"{where}: the section already has a walk-through in its Part file")
            continue
        try:
            w = load_walk(path, f"walkthrough_{slug}_{sid}".replace("-", "_"))
        except Exception as e:  # a source that does not run is reported with its name, like any other defect
            err(f"{where}: the source does not run: {type(e).__name__}: {e}")
            continue
        if not isinstance(w, dict):
            err(f"{where}: the source has no WALK")
            continue
        at = f"{where}.walkthrough"
        check.check_walk(w, at, kinds)
        check_size(w, at)
        check_room(w, at)
        built[(slug, sid)] = w

    if errors:
        print("\n".join("ERROR " + e for e in errors))
        print(f"{len(errors)} errors; nothing written")
        sys.exit(1)

    # What the folder should hold: one JSON for each source, in Part order and then section order, and the index.
    expected = {}
    entries = []
    for slug in order:
        sids = [s["id"] for s in parts.get(slug, []) if (slug, s["id"]) in built]
        if not sids:
            continue
        for sid in sids:
            expected[os.path.join(OUT, slug, f"{sid}.json")] = json.dumps(built[(slug, sid)], indent=2, ensure_ascii=False) + "\n"
        entries.append((slug, [(sid, camel(slug, sid)) for sid in sids]))
    expected[os.path.join(OUT, "index.ts")] = index_ts(entries)

    strays = []
    if os.path.isdir(OUT):
        for slug in sorted(os.listdir(OUT)):
            folder = os.path.join(OUT, slug)
            if os.path.isdir(folder):
                strays += [os.path.join(folder, n) for n in sorted(os.listdir(folder)) if n.endswith(".json") and os.path.join(folder, n) not in expected]

    problems = [f"NO SOURCE {rel(p)}" for p in strays]
    for path, text in expected.items():
        if not os.path.exists(path):
            problems.append(f"MISSING {rel(path)}")
        elif read(path) != text:
            problems.append(f"DIFFERS {rel(path)}")

    count = len(built)
    noun = "walk-through" if count == 1 else "walk-throughs"
    for (slug, sid), w in built.items():
        print(f"{slug}/{sid}: {len(w['steps'])} steps, {len(w['nodes'])} boxes, {len(w['metrics'])} readouts, {english_words(w)} English words")

    if CHECK:
        if problems:
            print("\n".join(problems))
            print(f"{len(problems)} differences; run python3 scripts/walkthroughs/build.py to build them")
            sys.exit(1)
        print(f"{count} {noun}: the files are up to date")
        return

    if strays:
        print("\n".join(f"NO SOURCE {rel(p)}: delete it, or add its source" for p in strays))
        print("nothing written")
        sys.exit(1)
    for path, text in expected.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"{count} {noun} written")


if __name__ == "__main__":
    main()
